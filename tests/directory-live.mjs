import { DOMParser } from 'linkedom';
import assert from 'node:assert/strict';
import { loadOperatorDirectory, loadStoryDirectory, loadMemoryDirectory, lookupPortraits } from '../directory.js';
globalThis.DOMParser = DOMParser;
const operators = await loadOperatorDirectory();
assert.ok(operators.operators.length > 400);
const sample = operators.operators.find(o => o.name === '絮雨');
assert.ok(sample);
assert.equal(sample.rarity, 5);
const images = await lookupPortraits([sample], 'portrait');
assert.ok(images['portrait:絮雨']);
console.log('Operator index and portrait lookup verified:', operators.operators.length);
const stories = await loadStoryDirectory();
const counts = Object.fromEntries(['main', 'events', 'intermezzi', 'other'].map(c => [c, stories.groups.filter(g => g.category === c).length]));
assert.ok(counts.main > 10);
assert.ok(counts.intermezzi > 0);
const chapter = stories.groups.find(g => g.title === '黑暗时代·上');
assert.ok(chapter?.links.some(l => l.title === '0-7 感染/BEG'));
console.log('Story chapter groups verified:', JSON.stringify(counts));
const memories = await loadMemoryDirectory();
assert.ok(memories.groups.length > 100);
assert.ok(memories.groups.some(g => g.title === '絮雨'));
console.log('Operator memory directory verified:', memories.groups.length);
